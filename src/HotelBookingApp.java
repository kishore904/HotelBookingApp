/**
 * -------------------------------------------------------
 * Hotel Booking Management System
 * Use Case 1: Application Entry & Welcome Message
 *
 * This program demonstrates the entry point of the
 * Hotel Booking application. It prints the application
 * name and version information when the program starts.
 *
 * @author Kishore
 * @version 1.0
 * -------------------------------------------------------
 */

public class HotelBookingApp {

    /**
     * Main method - Entry point of the application.
     * The JVM starts execution from this method.
     */
    public static void main(String[] args) {

        // Display welcome message
        System.out.println("======================================");
        System.out.println("      HOTEL BOOKING MANAGEMENT SYSTEM ");
        System.out.println("======================================");

        // Display version information
        System.out.println("Application Version : 1.0");

        // Display welcome text
        System.out.println("Welcome to the Hotel Booking Application!");

        // Inform that system is ready
        System.out.println("System initialized successfully.");

        // Application end
        System.out.println("======================================");
    }
}